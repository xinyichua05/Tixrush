package com.tixrush.order;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.CreationTimestamp;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;
import java.util.UUID;

/**
 * One ticket bought by one user.
 *
 * eventId/userId are plain ids, not @ManyToOne relations: we never need to load the
 * whole Event or User through an order, and plain ids keep the hot "buy" path simple.
 * The database still enforces that they exist (FOREIGN KEY in V3__create_orders.sql).
 *
 * Statuses (V4): CONFIRMED (v1-v3, v4 part 1), or PENDING_PAYMENT -> PAID / EXPIRED (v4 queue).
 * V9 adds PENDING_PAYMENT -> CANCELLED (the buyer gave the tickets back before paying).
 */
@Entity
@Table(name = "orders")
public class Order {

    public static final String CONFIRMED = "CONFIRMED";
    public static final String PENDING_PAYMENT = "PENDING_PAYMENT";
    public static final String PAID = "PAID";
    public static final String EXPIRED = "EXPIRED";
    /** The buyer cancelled before paying (V9). */
    public static final String CANCELLED = "CANCELLED";
    /** Orders that no longer hold any ticket: they went back on sale. */
    public static final List<String> RELEASED = List.of(EXPIRED, CANCELLED);

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "event_id", nullable = false)
    private Long eventId;

    @Column(name = "user_id", nullable = false)
    private Long userId;

    @Column(nullable = false, length = 20)
    private String strategy;

    @Column(nullable = false, length = 20)
    private String status = CONFIRMED;

    /** Only set for queued orders (v4 complete). Generated by the API before the order exists in the DB. */
    @Column(name = "reservation_id", unique = true)
    private UUID reservationId;

    @Column(name = "expires_at")
    private Instant expiresAt;

    @Column(name = "paid_at")
    private Instant paidAt;

    /** Which ticket type (null = old single-pool event). */
    @Column(name = "ticket_type_id")
    private Long ticketTypeId;

    /** How many tickets this one order holds (1-4). Old-style orders: always 1. */
    @Column(nullable = false)
    private int quantity = 1;

    /** Price of ONE ticket when the order was made (prices may change later). null = old-style. */
    @Column(name = "unit_price", precision = 10, scale = 2)
    private BigDecimal unitPrice;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    protected Order() {
    }

    public Order(Long eventId, Long userId, String strategy) {
        this.eventId = eventId;
        this.userId = userId;
        this.strategy = strategy;
    }

    public Long getId() { return id; }
    public Long getEventId() { return eventId; }
    public Long getUserId() { return userId; }
    public String getStrategy() { return strategy; }
    public String getStatus() { return status; }
    public UUID getReservationId() { return reservationId; }
    public Instant getExpiresAt() { return expiresAt; }
    public Instant getPaidAt() { return paidAt; }
    public Instant getCreatedAt() { return createdAt; }
    public Long getTicketTypeId() { return ticketTypeId; }
    public int getQuantity() { return quantity; }
    public BigDecimal getUnitPrice() { return unitPrice; }
}
